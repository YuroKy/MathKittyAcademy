let nextTopicOrder = 1

export const atlasLocations: AtlasLocation[] = locationSeeds.map(
  ({ topicTitles, ...location }) => ({
    ...location,
    topics: topicTitles.map((title, index) => {
      const order = nextTopicOrder
      nextTopicOrder += 1
      return {
        id: `${location.id}-${index + 1}`,
        order,
        title,
        liveTopicId: curriculumTopicIdByAtlasTitle[title],
        isBoss: index === topicTitles.length - 1,
      }
    }),
  }),
)

export const atlasTopicCount = atlasLocations.reduce(
  (total, location) => total + location.topics.length,
  0,
)

export function findAtlasLocation(locationId: string): AtlasLocation | undefined {
  return atlasLocations.find((location) => location.id === locationId)
}

export function findAtlasTopic(topicId: string): AtlasTopic | undefined {
  return atlasLocations.flatMap((location) => location.topics).find((topic) => topic.id === topicId)
}
