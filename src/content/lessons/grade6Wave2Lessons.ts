import type { FullLessonContent, LessonExerciseTemplate, TopicPreview } from '@/types/domain'

import { grade6Wave2Qa, type Grade6Wave2TopicId } from './grade6Wave2Qa'

type Difficulty = 1 | 2 | 3

function preview(
  topicId: Grade6Wave2TopicId,
  hook: string,
  question: string,
  choices: string[],
  correctChoiceIndex: number,
  explanation: string,
): TopicPreview {
  return {
    topicId,
    hook,
    question,
    choices,
    correctChoiceIndex,
    explanation,
    challengeLabel: 'Перевірити на новому прикладі',
  }
}

function numeric(
  templateId: string,
  skillIds: string[],
  title: string,
  prompt: string,
  expectedAnswer: string,
  hints: [string, string],
  solutionSteps: string[],
  difficulty: Difficulty = 2,
): LessonExerciseTemplate {
  return {
    templateId,
    skillIds,
    difficulty,
    kind: 'numericInput',
    title,
    prompt,
    expectedAnswer,
    answerSpec: { kind: 'rational', value: expectedAnswer },
    validationStrategy: 'rational',
    hints,
    simplerExplanation: `Виконуй по одній дії. ${solutionSteps.join(' ')}`,
    solutionSteps,
  }
}

function choice(
  templateId: string,
  skillIds: string[],
  title: string,
  prompt: string,
  choices: string[],
  expectedAnswer: string,
  hints: [string, string],
  solutionSteps: string[],
  difficulty: Difficulty = 2,
): LessonExerciseTemplate {
  return {
    templateId,
    skillIds,
    difficulty,
    kind: 'multipleChoice',
    title,
    prompt,
    choices,
    expectedAnswer,
    answerSpec: { kind: 'singleChoice', value: expectedAnswer },
    validationStrategy: 'choice',
    hints,
    simplerExplanation: `Перевір кожен варіант за правилом. ${solutionSteps[0] ?? ''}`,
    solutionSteps,
  }
}

function matching(
  templateId: string,
  skillIds: string[],
  title: string,
  prompt: string,
  pairs: Record<string, string>,
): LessonExerciseTemplate {
  return {
    templateId,
    skillIds,
    difficulty: 2,
    kind: 'matching',
    title,
    prompt,
    expectedAnswer: Object.entries(pairs)
      .map(([left, right]) => `${left} → ${right}`)
      .join('; '),
    answerSpec: { kind: 'matching', pairs },
    matchingPairs: Object.entries(pairs).map(([left, right]) => ({ left, right })),
    hints: ['Перевір кожну пару окремо.', 'Почни з відповідності, яку бачиш одразу.'],
    simplerExplanation: 'Кожному запису зліва відповідає рівно один запис справа.',
    solutionSteps: Object.entries(pairs).map(([left, right]) => `${left} відповідає ${right}.`),
  }
}

function lesson(
  topicId: Grade6Wave2TopicId,
  data: Omit<FullLessonContent, 'topicId' | 'qa'>,
): FullLessonContent {
  return { topicId, qa: grade6Wave2Qa[topicId], ...data }
}

